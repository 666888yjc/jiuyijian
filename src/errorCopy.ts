/** 取一个错误码对用户说的话；未知码回兜底句（但调用方仍要把码本身显示出来） */
export function errorCopy(code: string | null | undefined): string {
  const base = String(code ?? "").trim().split("@")[0];
  return ERROR_COPY[base] ?? ERROR_COPY.unknown_extract_failure;
}
