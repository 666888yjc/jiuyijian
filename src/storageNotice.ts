// 这份任务里的资料**到底存在哪里**——一句话说明（回归层 A 直接 import 真调用取证）。
//
// 为什么单独成模块、且由"任务"而不是"账号"驱动（R44 的真缺陷）：
// 页头徽章说的是**账号**状态（已同步 · 某某），而资料存在哪里由**这个任务**决定：
// 内置示例任务按设计不上云，登录用户在离线时新增的资料也只会留在本机。
// 此前 DocsPage 的中间分支只看"有没有登录"就说"上传的原件将加密保存到站点存储"，
// 于是在示例任务里当着登录用户的面**把话说反了**——对一款处理病历的产品，
// "这份资料会不会离开我的设备"是必须答对的问题，答错的严重性不低于把药名写错。
//
// 写法纪律（R46 构建指纹试验用注释，稍后回退）：每句话都只说**当前这个任务**成立的事实，不承诺没发生的事，也不猜原因。

/** 后端连通性是三件事实之一（另两件：登录了吗、这个任务可同步吗）。类型定义在 sync 层，这里只声明形状以免成环。 */
export type BackendStatus = "checking" | "up" | "down";

/** 拿不准云端时，一律走"无从确认"这一档：这是 R68 全部五条文案共用的判据 */
export function backendConfirmed(backend: BackendStatus): boolean {
  return backend === "up";
}

export interface StorageNoticeInput {
  /** 云端链路对该任务实际可用（= serverMode && signedIn && isSyncable(task)） */
  serverUpload: boolean;
  signedIn: boolean;
  serverMode: boolean;
  /** 后端摸没摸着（`sync.backend`）——R68 之前这句话缺这一格，于是离线时也让用户去"登录" */
  backend: BackendStatus;
  /** 任务 id 不是 UUID ⇒ 内置示例任务（脱敏模拟数据） */
  demoTask: boolean;
}

export function storageModeNotice(i: StorageNoticeInput): string {
  if (i.serverUpload) {
    return "原件加密保存在站点存储中，识别由云端模型完成，结果一律进入「待确认」，不会自动写入交接单。";
  }
  if (i.signedIn && i.serverMode && i.demoTask) {
    return "你是登录状态，但这个任务是内置示例任务（脱敏模拟数据）：它的资料只保存在本机浏览器，不会上传到站点存储，也不会送云端识别。要走云端链路，请从任务列表新建一个任务。";
  }
  if (i.signedIn && i.serverMode) {
    return "这个任务目前不会上云（里面有只在本地保存的资料，例如离线时新增的）：在这个任务里继续上传的资料同样只留在本机浏览器。要把原件存进站点存储，请从任务列表新建一个任务。";
  }
  if (i.backend === "checking") {
    return "正在确认云端连接：在确认之前，资料只保存在这台设备的浏览器里。";
  }
  if (i.backend === "down") {
    // 这一句以前是「登录后可加密上传并云端识别」：云端不可达时登录页根本打不开，
    // 等于把一个此刻做不到的动作摆成出路（R40 在页头修掉的是同一类，这是第二处）。
    return "云端此刻不可达（或本版本未部署后端）：资料只保存在这台设备的浏览器里，不会离开这台设备。恢复连接后可以从任务列表新建一个任务走云端链路。";
  }
  return "当前为本地模式：资料仅存本机浏览器。登录后可加密上传并云端识别。";
}

/**
 * 删除确认里"会动到什么"。同一类缺陷的第二处：这句原先无条件说"其**云端原件**不再出现"，
 * 而本机模式／示例任务的资料从来没有云端原件——等于告诉家属有一台服务器上有他父亲病历的副本。
 * @param storedInCloud 这条资料是否真有站点存储里的原件（有 objectPath 且任务可同步）
 */
export function deleteNotice(storedInCloud: boolean): string {
  return storedInCloud
    ? "删除后此资料及其云端原件不再出现在列表与摘要中；引用它的识别字段将退回「待确认」。"
    : "删除后这条记录从本机浏览器里移除（它从来没有离开过这台设备）；引用它的识别字段将退回「待确认」。";
}

/**
 * 云端不可达时删除一个"服务器上确有原件"的任务，屏幕上必须说清这次删到了哪里（R73）。
 * 说错方向的代价与写错药名同级：家属会按"已经删干净了"来决定下一步（把设备递给别人、清相册、不再管它）。
 */
export function deferredDeleteNotice(): string {
  return "云端此刻不可达，这次删除先落在本机：这条任务已从你的列表里删掉，但服务器上那一行（连同加密存的原件）要等恢复连通后才能补删。补删前它不会出现在应用里，我们会在下次连通时自动做，若失败会在页头说明。";
}

/**
 * 隐私页"删除操作立即生效"那条断言。它原先是无条件写的，而离线删除只删到本机（R73）——
 * 一行说"云端的原件也不见了"的话，在云端不可达时是**按下删除键时唯一的依据**，说错就要负责。
 */
export function taskDeleteStatement(i: { serverUpload: boolean; backend: BackendStatus }): string {
  const docs = "删除资料后相关字段退回「待确认」；";
  if (i.backend !== "up") {
    return `删除操作${docs}删除任务后其全部内容不再出现在这台设备的任何产品入口，仅保留一条不含资料内容的删除留痕。⚠ 云端此刻不可达：如果这条任务的原件存在站点存储里，服务器那份要等恢复连通后才能删干净，本机已记下这次删除，下次连通会自动补删。`;
  }
  return `删除操作${docs}删除任务后其全部内容（含该任务在云端的原件，若有）不再出现在任何产品入口，仅在下方「处理与操作记录」保留一条不含资料内容的删除留痕。`;
}

/**
 * 下面这组是 R45 收敛出来的**唯一口径**：任务列表、隐私页、清除确认以前各自写了一份
 * "数据在哪里"，于是同一件事在三个页面上有三种说法（其中两处还把"账号已登录"当成"这个任务在云端"）。
 * 所有页面都必须经过这里，不许再自带裸断言。
 */
export type DataLocation = "cloud" | "local" | "unconfirmed";

/**
 * 这个任务的数据此刻到底在哪里。
 * R68 加的第三态：`!syncable` 的任务（内置示例任务）按设计从来不上云，这一条**不依赖云端可达性**，
 * 所以离线也照样能肯定地说「仅在本机」；反过来，一个可同步的任务在云端不可达时被标成「仅在本机」
 * 是句假话——它上一次连通时可能早就传上去了。那种情况下只能说"没确认"。
 */
export function dataLocationOfTask(i: {
  backend: BackendStatus;
  serverMode: boolean;
  signedIn: boolean;
  syncable: boolean;
}): DataLocation {
  if (!i.syncable) return "local";
  if (i.backend !== "up") return "unconfirmed";
  return i.serverMode && i.signedIn ? "cloud" : "local";
}

export function storageBadgeLabel(loc: DataLocation): string {
  return loc === "cloud" ? "云端保存" : loc === "unconfirmed" ? "位置未确认" : "仅在本机";
}

export function storageBadgeTitle(loc: DataLocation): string {
  return loc === "cloud"
    ? "这个任务的原件与识别结果保存在站点私有存储，其他登录用户不可访问。"
    : loc === "unconfirmed"
      ? "云端此刻不可达，无法核对服务器上的副本状态：这台设备上一定有这份资料；上一次连通时上传过的，可能仍在云端。恢复连接后这里会自动重新判定。"
      : "这个任务的资料只保存在本设备浏览器里，没有上传到任何服务器（内置示例任务按设计不上云；离线时新增过资料的任务也会留在这里）。";
}

/** 隐私页"当前版本数据说明"的第一句 */
export function privacyDataStatement(i: { backend: BackendStatus; serverMode: boolean; signedIn: boolean }): string {
  if (i.serverMode && i.signedIn) {
    return "已登录：标注「云端保存」的任务保存在你的账号下，原件加密存于站点私有存储，其他登录用户不可访问；标注「仅在本机」的任务（含内置示例任务、以及离线时新增过资料的任务）从未上传到任何服务器。";
  }
  if (i.backend !== "up") {
    return "云端此刻不可达：本次会话没有向服务器写入或核对过任何数据，你现在看到的都是这台设备里留存的内容；账号下是否另有副本，要等恢复连接后才能确认（标注「位置未确认」的任务就是这一种）。";
  }
  return "未登录：所有任务与资料仅保存在本设备浏览器中，未上传任何服务器。";
}

/**
 * 「本机与服务器各有一份」这一档的中文标签——页头那颗芯片与任务列表卡片上的标位共用这一个串，
 * 不许各写一份（R78 那次"同一件事抄两处，早晚不一致"的老形状；R84 把列表标位接进来时钉死）。
 */
export const CONFLICT_LABEL = "本机与服务器各有一份";

/**
 * 本机与服务器各有一份、且两边都在上次一致之后被改过（R74）。
 * 这一句存在的全部理由：这种时候界面**不许**说「已同步」，也不许假装"我们帮你合并好了"——
 * 合并要人做判断，当前版本没有自动合并，说反了就是误导。
 *
 * R84 改掉了最后那半句，因为 R81 在真浏览器里把它证伪了：原文写"在另一台设备上会看到同样的提示"，
 * 实测换设备（或清除本机数据）之后**什么提示都没有**，页头直接改口「已同步」，而本机那一份被无声丢掉。
 * 现在说的是量出来的一半事实：另一台设备只会看到服务器那份、本机这份带不过去、清掉就没了且无法恢复，
 * 并且把唯一真有的保命出口（「隐私与数据」页的「导出我的数据（JSON）」）指给人。
 * "不再存到服务器"这一句的范围是**挂着这一档的那几条任务**（`src/sync.tsx` 是逐条 `continue`，不是整机暂停），
 * 所以措辞必须点到那几条为止——写成"这台设备上再改的东西都不存"就是又一次把界面说的话超出代码做的事。
 * "另存一份"这一句在 R88 补上了限定：导出的那份**不含原件图片与 OCR 原文**（`PrivacyPage` 的导出对话框当场这么写着），
 * 所以句子必须自己说清——冲突争的是"核对内容哪一份算"，但一个以为 JSON 里有全部病历原件的家属
 * 完全可能把"留住这一份"读成"连图片也在里面"（R87 在真浏览器上拦下那个 blob 现读过载荷才确认）。
 */
export function syncConflictNotice(count: number): string {
  return `有 ${count} 个任务：这台设备上有一份，服务器上也有一份，两边都在上次同步之后被改过。为了不把任何一方的核对覆盖掉，这两份这次都没被改动——本机这份继续显示给你用，服务器上那份原样留着，它们还没有合并（当前版本不做自动合并；要定留哪一份，进这条任务页按「并排看这两份，挑一份留下」把两份看完再挑——挑中的那份会替换掉另一份，而我方没有地方能把被替换掉的那一份取回来）。挂着这一档时，这几条任务在这台设备上再改的东西只留在本机、不会存到服务器，别的任务照旧会存；要把本机这一份留住，可以在「隐私与数据」页按「导出我的数据（JSON）」另存一份——它含任务、字段、行动与复诊摘要这些核对内容，但不含原件图片与 OCR 原文（要把原件也留住，得靠交接单打印或另存为 PDF）。另一台设备只会看到服务器那一份：本机这份不会被带过去，清除本机数据就会把它丢掉，而且无法恢复。打印交接单前，请把这几条在本设备上逐项核对一遍。`;
}

/** 「清除本机全部数据」确认框：说清哪些会没了、哪些不受影响 */
export function wipeConsequence(i: { backend: BackendStatus; serverMode: boolean; signedIn: boolean }): string {
  if (i.serverMode && i.signedIn) {
    // R73：删除账也在本机存储里，一起被清掉是有后果的——不写进这句，家属就少了一次按下清除键前该知道的信息
    return "标注「云端保存」的任务与原件不受这次清除影响，登录后仍会保留；标注「仅在本机」的任务与资料会被立即删除且无法恢复。本机那份「已删除但服务器上还没删干净」的清单也会被一起清掉——如果你曾是在离线状态下删的任务，重新登录后它有可能再出现一次（届时再删一次即可，联网状态下会连服务器那份一起删掉）。另外本机还记着每个任务「上次与服务端一致」的时间点，它也会被一起清掉：清掉后应用就无从判断这台设备和服务器上的两份各自动过没有，第一次连通时会把这些任务标成「本机与服务器各有一份」并暂停自动同步它们（不覆盖任何一方，需要你逐项核对）。";
  }
  if (i.backend !== "up") {
    // 旧句子在这里无条件说「当前没有云端副本」——云端摸不着时这恰恰是**无从确认**的事，
    // 拿它当依据按下清除键，家属以为云端也没有，而账号里可能正躺着原件。
    return "云端此刻不可达：这次清除会立即删除这台设备上的全部本地数据且无法恢复；账号下是否另有云端副本这次无法确认，且不会被这次清除动到。";
  }
  return "当前没有云端副本：清除后本设备不再保留任何数据，且无法恢复。";
}

