// 就医笺 · 红线②"对用户怎么说"的唯一一份（R64）
//
// 为什么单列：这句话此前在六个地方各写一遍（页脚、任务列表、交接单预览、交接单导出文本、
// 复诊摘要屏上、摘要导出文本 ⇒ 五句），而且**多数句子漏了"处方"**——
// 只有页脚写全了"诊断、处方或用药建议"；医生看到的那张纸上、转出去的导出文本里都只写"诊断/用药"。
// 红线本身点名的正是"诊断、处方、改药"这三件。措辞各写一份的必然结果就是漏一件而没人发现。
//
// 两条纪律：
//  ① 三件对象（诊断／处方／用药建议）必须**每个出口都出现**——回归层 A 对着本表现取比对，
//     加第四个对象会逼所有出口一起过一遍，漏一处即红；
//  ② 句子仍然只说"我们不提供什么 + 该找谁"，**不解释医学、不给任何建议**（红线②本身）。
// "紧急情况请立即就医"是引导就医，不是分诊判断，因此留在页脚出口。

/** 每个边界声明出口都必须覆盖到的三件事（红线②点名的就是这三件） */
export const BOUNDARY_OBJECTS = ["诊断", "处方", "用药"] as const;

/** 六个出口的完整句子；页面与导出文本都从这里取，不再自己写一份 */
export const BOUNDARY_NOTICES = {
  /** 全站页脚（任何页面都在） */
  footer: "就医笺只做信息整理与就诊交接，不提供诊断、处方或用药建议；如有紧急情况请立即就医。",
  /** 任务列表顶部：家属开应用第一眼看到的边界 */
  taskList: "本工具不做诊断，不提供处方或用药建议。",
  /** 交接单纸上（外发给医生看的那一份） */
  sheet: "由患者/照护者整理，内容均已逐项与原件核对；标注「补充」的为患者自述。本单不是医疗记录，不提供诊断、处方或用药建议，具体请以医生面诊为准。",
  /** 复诊摘要屏上 */
  summary: "由患者/照护者整理；“自述”内容未经医学核实，不构成诊断、处方或用药建议。",
  /** 复诊摘要导出文本（跟着文字一起被转发出去） */
  summaryText: "本摘要由患者/照护者根据已核对资料整理，仅为就诊交接信息，不构成诊断、处方或用药建议；医学判断以医生为准。",
} as const;

/** 某个出口是否真的覆盖了三件事（判据与产品都用这一个函数，避免"判据自己另算一套"） */
export function noticeCoversBoundary(notice: string): string[] {
  const text = String(notice ?? "");
  return BOUNDARY_OBJECTS.filter((o) => !text.includes(o));
}
